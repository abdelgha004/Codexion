#include "../codexion.h"

long	get_time_ms(void)
{
	struct timeval	tv;

	gettimeofday(&tv, NULL);
	return (tv.tv_sec * 1000 + tv.tv_usec / 1000);
}

long	elapsed_time(t_config *conf)
{
	return (get_time_ms() - conf->start_time);
}